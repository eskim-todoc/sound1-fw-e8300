"""SUVR «측정/검토 내용» - 실제 코드 분석 결과.

키는 원본 SU-ID(제외 반영 전) 다. 재번호와 무관하게 유닛을 가리킨다.
각 항목은 소스 본문을 실제로 읽고 확인한 사실만 적는다. 지어내지 않는다.
확인하지 못한 것은 여기 넣지 않는다.

  crit : 통과 기준 (SUVC/SUVR 공통)
  meas : 측정/검토 내용 (SUVR 전용)
"""

F = {}


def add(key, crit, meas):
    assert key not in F, u'키 중복: %s' % key      # 덮어쓰기 사고 방지
    F[key] = {'crit': crit, 'meas': meas}


def merge(other):
    for k, v in other.items():
        assert k not in F, u'키 중복: %s' % k
        F[k] = v


