def make_tests(baseline):
    book=baseline['books']['integration']['sheets']
    main=book['보고서_통합시험']['cells']; helper=book['시험 보조자료']['cells']
    groups={i:[] for i in range(1,18)}
    for r in range(6,121):
        label=helper.get('B'+str(r),''); hit=re.match(r'^\[(\d+)\]',label)
        if not hit: continue
        test=int(helper['A'+str(r)].rsplit('-',1)[1]); case=int(hit[1])
        assert case==len(groups[test])+1,(test,case)
        expected=clean_expected(EXPECTED_OVERRIDE.get((test,case),label))
        expected='조건 '+expected
        result=CONFIRMED_RESULTS.get((test,case),RESULTS[test][case-1])
        # RTT 표제 자체가 조건 연결을 포함하면 중복 '검증' 표제를 만들지 않는다.
        if not result.startswith(f'검증 [{case}]'): result=f'검증 [{case}]\n'+result
        groups[test].append(dict(number=case,expected=expected,result=result,sourceHelperRow=r))
    tests=[]
    for i,cases in groups.items():
        assert len(cases)==len(RESULTS[i]),(i,len(cases),len(RESULTS[i]))
        row=i+24; meta={col:main.get(col+str(row),'') for col in 'BCDEFGHIJKL'}
        if i in PREP: meta['J']=PREP[i]
        for col in ['J','K','L']:
            meta[col]=meta[col].replace('·','/').replace('허가','실행 허용')
        if i==3: meta['K']='마이크 표본은 디지털 입력이다. 복사 완료 플래그는 실제 복사 경로에서 읽는다. 직접 게인/fade 호출 결과와 정상 루프의 적용 결과를 구분한다.'
        if i==4: meta['K']='판정 대상은 PCM 전송 전 디지털 버퍼와 모드 전환이다.'
        if i==5: meta['L']='각 입력 조건에서 실제 HEAR 완료 이벤트 후 혼합 최대값/FFT 결과를 읽는다. 별도 매핑 출력100을 넣은 CIS 조건은 연속 세 구간의 전극 인덱스/크기/NOP를 대조한다.'
        if i==10: meta['K']='판정 범위는 E8300의 SPI 수신 이후 명령 처리와 응답이다.'
        if i==12: meta['K']='응답 유효 데이터와 저장 배열의 길이 필드를 구분한다. 유닛 보조 RTT는 해당 입력 조건의 수치 비교 자료로 사용한다.'
        status='통과'
        tests.append(dict(id=i,sourceRow=row,meta=meta,cases=cases,status=status,
            originalCriteria=main['M'+str(row)],sourceResult=main['N'+str(row)]))
    return tests
