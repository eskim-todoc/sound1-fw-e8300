from draw_architecture import Canvas

def lanes(title, names, fill, height=1080):
    c=Canvas((2100,height))
    c.text((1050,55),title,44,True)
    for (left,right),name in zip([(40,650),(750,1360),(1460,2070)],names):
        c.dash((left,115,right,height-100))
        c.text(((left+right)/2,165),name,40,True)
    c.box((25,225,2085,315),fill=fill,radius=5)
    return c

