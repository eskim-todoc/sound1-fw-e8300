"""Independent interval references for CFX-023/031/032, not product results.

SDK contracts: sk5_cfx_dsp_data_conversions.h describes 10*log10(power)
and 10**(dB/10); local Hardware Reference, Math Accelerators, Log2/Exp2
describes less than half-bit error and m8p24/m1p47 precision. SDK conversion
uses the Q20/Q23 factors below. Conservative intervals include one extra
retained-bit rounding allowance, conversion-factor quantization and each
integer truncation. Bounds are generated BEFORE executing target code.

Only the documented positive inputs <=262143 are used (x<<5 remains a
positive 24-bit word). These references are not a hardware execution proof.
"""
from __future__ import annotations

import argparse
import itertools
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "src/1__cfx/test/tdc_ut_numeric_reference_cfx.h"
Q16 = 1 << 16
Q23 = 1 << 23
P_Q23 = 1258291
NORMALIZE_Q16 = 5163793
PWR_TO_DB_Q20 = 0x302A30
DB_TO_PWR_Q23 = 0x2A854B
AGC_INPUT = (1, 8, 128, 4096, 65536, 262143)
MAPPING_INPUT = (0, 1, 8, 64, 512, 4096, 16384, 262143)
ATTENUATION = ((47999, -1661530), (4744, -4786621))
AMPLIFY = (0, 973249)
NOISE = (481268, 542096)
NOISE_GATE = -7700296
ROTATION = -6209352


def hull(values):
    values = tuple(values)
    return min(values), max(values)


def log_db_bounds(x: int) -> tuple[int, int]:
    """Q8.16 dB interval from analytic log, not a product call/lookup."""
    log2 = math.log2(x * 32 / 2**47)
    ideal_q16 = log2 * 10 * math.log10(2) * Q16
    # MSB Log2 truncation <1 Q16 bit; half a bit even if interpreted at
    # the retained precision; one conversion rounding bit; exact factor bias.
    error = (1.5 * PWR_TO_DB_Q20 / 2**20 + 1
             + abs(log2) * abs(PWR_TO_DB_Q20 / 2**20 - 10 * math.log10(2)) * Q16)
    return math.floor(ideal_q16 - error), math.ceil(ideal_q16 + error)


def exp_power_q23_bounds(db: tuple[int, int]) -> tuple[int, int]:
    """dB Q8.16 -> power Q1.23, including Exp2 input/output truncation."""
    # Actual SDK factor is part of the declared conversion contract.
    lo, hi = (v / Q16 * DB_TO_PWR_Q23 / Q23 for v in db)
    # One m8p24 input quantum and half a retained Q1.23 output bit plus
    # one final truncation quantum conservatively cover the documented error.
    return (max(0, math.floor(2 ** (lo - 1 / 2**24) * Q23 - 1.5)),
            min(Q23 - 1, math.ceil(2 ** (hi + 1 / 2**24) * Q23 + 1.5)))


def power_bounds(x: int) -> tuple[int, int]:
    if x < 1:
        return 0, 0
    db = tuple(v * P_Q23 // Q23 for v in log_db_bounds(x))
    return tuple(v * NORMALIZE_Q16 // Q23 for v in exp_power_q23_bounds(db))


def gain_goal(db: int, volume: int) -> int:
    if db < NOISE_GATE:
        return ((2 * db // 16) + NOISE[volume] - db // 16) * 16
    if db > ROTATION:
        slope, bias = ATTENUATION[volume]
        return slope * db // Q16 + bias - db
    return AMPLIFY[volume]


def agc_bounds(x: int, volume: int):
    db = log_db_bounds(x)
    goal = hull(gain_goal(v, volume) for v in db)
    smooth = hull(v * (655 if v >= 0 else 62259) // Q16 for v in goal)
    linear = tuple(v // 2 for v in exp_power_q23_bounds(tuple(v - 1972830 for v in smooth)))
    return goal, smooth, linear


def coefficient_bounds(t: int, c: int):
    xmin, xmax = power_bounds(16), power_bounds(4096)
    diff = (xmax[0] - xmin[1], xmax[1] - xmin[0])
    assert diff[0] > 0
    # The documented fixed-point ratio, independently rationally evaluated.
    # One Q24.24 division result bit cannot exceed one after >>13.
    a = ((c - t) * 2**24 // diff[1] - 1,
         (c - t) * 2**24 // diff[0] + 1)
    b = (c * 256 - a[1] * xmax[1] // Q16,
         c * 256 - a[0] * xmax[0] // Q16)
    return a, b


def mapping_bounds(x: int, t: int, c: int, mute: int):
    a, b = coefficient_bounds(t, c)
    p = power_bounds(x)
    raw = hull((av * pv // Q16 + bv) // 256
               for av, pv, bv in itertools.product(a, p, b))
    def limit(y):
        return min(c, (0 if y < t else y) if mute == 1 else max(t, y))
    return tuple(limit(v) for v in raw)


def references():
    agc = [dict(input=x, volume=volume * 9,
                bounds=agc_bounds(x, volume))
           for volume in range(2) for x in AGC_INPUT]
    coeff = [dict(t=50 + i % 4, c=150 + i % 4,
                  bounds=coefficient_bounds(50 + i % 4, 150 + i % 4))
             for i in range(32)]
    mapping = [dict(input=x, bounds=[mapping_bounds(x, 50, 150, mute)
                                    for mute in (1, 2)]) for x in MAPPING_INPUT]
    return dict(agc=agc, coeff=coeff, mapping=mapping)


def render_header(data):
    lines = ["/* Generated by tests/unit/cfx_numeric_reference.py; do not tune to target output.",
             " * Bounds use SDK format/accuracy contracts and independent math. */",
             "#ifndef TDC_UT_NUMERIC_REFERENCE_CFX_H",
             "#define TDC_UT_NUMERIC_REFERENCE_CFX_H",
             "#if defined(TDC_UNIT_TEST)",
             "static const int s_tdc_ut_agc_full[12][8] = {"]
    for row in data["agc"]:
        vals = [row["input"], row["volume"], *itertools.chain.from_iterable(row["bounds"])]
        lines.append("    {" + ",".join(map(str, vals)) + "},")
    lines += ["};", "static const int s_tdc_ut_coeff_full[4][4] = {"]
    for row in data["coeff"][:4]:
        lines.append("    {" + ",".join(map(str, itertools.chain.from_iterable(row["bounds"]))) + "},")
    lines += ["};", "static const int s_tdc_ut_mapping_full[8][5] = {"]
    for row in data["mapping"]:
        vals = [row["input"], *itertools.chain.from_iterable(row["bounds"])]
        lines.append("    {" + ",".join(map(str, vals)) + "},")
    lines += ["};", "#endif", "#endif", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="mechanically regenerate checked-in reference header")
    args = parser.parse_args()
    data = references()
    header = render_header(data)
    if args.write:
        HEADER.write_text(header, encoding="utf-8")
    else:
        assert HEADER.read_text(encoding="utf-8") == header, "stale independent numeric reference header"
    out = ROOT / "tmp/unit-tests/cfx-numeric-reference"
    out.mkdir(parents=True, exist_ok=True)
    (out / "reference.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    print("CFX NUMERIC_REFERENCE_OK: AGC12, coefficients32, mapping8x2; no target execution")


if __name__ == "__main__":
    main()
