int ci_fft_init_window_coeff(void)
{
    int ret;

    int *addr_fft_windowBuff_for_HEAR;
    int *addr_fft_windowBuff_for_FS;

    ret = ci_fft_read_window_coeff();

    if (ret < 0)
    {
        ret = ci_fft_write_window_coeff();
    }

    if (0 <= ret)
    {
        addr_fft_windowBuff_for_HEAR = (int *) (HEAR_C0MEM_LSB_SIGNED_BASE + (FFT_Size * 4));
        addr_fft_windowBuff_for_FS   = (int *) OTE_1_5_GEN_FS_HANN_WINDOW_COEFF_BASE_ADDR;

        for (int i = 0; i < FFT_Size; i++)
        {
            addr_fft_windowBuff_for_HEAR[i] = addr_fft_windowBuff_for_FS[i];
        }
    }

    return ret;
}

